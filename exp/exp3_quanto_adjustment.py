"""Experiment 3: contractual quanto adjustment to the par fixed margin
(Section 6.3 of Ding, Liu and Rutkowski, "Choice of Collateral Currency in
Differential Swaps"), isolating the stochastic cross-currency correction
generated by the contractual €STR leg.

The quanto adjustment (eq. 6.3) is

    Delta_kappa_i^q(gamma) = kappa_star(T_0,n;beta,gamma,i) - kappa_star^{no-qf}(T_0,n;beta,gamma,i),

where kappa_star^{no-qf} replaces the deterministic quanto correction
Gamma_0^{qf} by 1 in the I^{(2)} pricing component (Section 6.3). It is
computed for gamma=1 (so that Delta_kappa_i^q(gamma)=gamma*Delta_kappa_i^q(1)
holds trivially), for both collateral currencies, over a grid of the
foreign-rate/FX correlation rho_23 and the FX volatility sigma_bar. The
foreign-measure drift constant a_hat is held fixed (Section 6.3): only the
domestic-measure drift c_hat = a_hat - sigma_hat*sigma_bar*rho_23 moves with
the grid, consistent with the Girsanov shift of Section 3.1.

Run: python -m exp.exp3_quanto_adjustment
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from src.config import (
    A_D, A_HAT, B_D, B_F, EXP3_GAMMA, EXP3_MATURITY, EXP3_RHO23_GRID,
    EXP3_SIGMA_BAR_GRID, NET_CARRY_EUR_BP, NET_CARRY_USD_BP, Q0, R0_D, R0_F,
    RHO_12, RHO_13, SIGMA_D, SIGMA_F, BETA_FULL,
)
from src.pricing import ModelParams, par_fixed_margin, par_fixed_margin_no_quanto


def _params_for(rho_23: float, sigma_bar: float) -> ModelParams:
    """Model parameters with a_hat fixed and c_hat recomputed for the given
    (rho_23, sigma_bar) point (Section 6.3): c_hat = a_hat - sigma_hat*sigma_bar*rho_23."""
    c_hat = A_HAT - SIGMA_F * sigma_bar * rho_23
    return ModelParams(r0_d=R0_D, b_d=B_D, sigma_d=SIGMA_D, a_d=A_D,
                        r0_f=R0_F, b_f=B_F, sigma_f=SIGMA_F, c_hat=c_hat, a_hat=A_HAT,
                        q0=Q0, sigma_bar=sigma_bar, rho_12=RHO_12, rho_13=RHO_13, rho_23=rho_23)


def quanto_margin_adjustment(mp: ModelParams, net_carry_bp: float) -> float:
    """Delta_kappa_i^q(gamma=1), in decimal (Section 6.3, eq. 6.3)."""
    kappa_with_qf = par_fixed_margin(0.0, EXP3_MATURITY, EXP3_GAMMA, mp, BETA_FULL, net_carry_bp)
    kappa_no_qf = par_fixed_margin_no_quanto(0.0, EXP3_MATURITY, EXP3_GAMMA, mp, BETA_FULL, net_carry_bp)
    return kappa_with_qf - kappa_no_qf


def run_sensitivity() -> list[dict]:
    """Full grid of rho_23 x sigma_bar, both collateral currencies
    (Section 6.3, Figure 2)."""
    rows = []
    for sigma_bar in EXP3_SIGMA_BAR_GRID:
        for rho_23 in EXP3_RHO23_GRID:
            mp = _params_for(rho_23, sigma_bar)
            adj_usd_bp = quanto_margin_adjustment(mp, NET_CARRY_USD_BP) * 1e4
            adj_eur_bp = quanto_margin_adjustment(mp, NET_CARRY_EUR_BP) * 1e4
            rows.append({
                "rho_23": rho_23,
                "sigma_bar": sigma_bar,
                "quanto_adjustment_usd_collateral_bp": adj_usd_bp,
                "quanto_adjustment_eur_collateral_bp": adj_eur_bp,
                "usd_eur_abs_diff_bp": abs(adj_usd_bp - adj_eur_bp),
            })
    return rows


def run_gamma_linearity_check() -> dict:
    """Confirm Delta_kappa_i^q(gamma) = gamma * Delta_kappa_i^q(1) (eq. 6.3) by
    comparing the gamma=1 adjustment against the adjustment recomputed
    directly at gamma=0.5 and gamma=0."""
    from src.pricing import ModelParams as _MP  # local import avoided elsewhere; keep module tidy
    mp = _params_for(0.10, 0.075)
    out = {}
    for gamma in (0.0, 0.5, 1.0):
        kappa_with_qf = par_fixed_margin(0.0, EXP3_MATURITY, gamma, mp, BETA_FULL, NET_CARRY_USD_BP)
        kappa_no_qf = par_fixed_margin_no_quanto(0.0, EXP3_MATURITY, gamma, mp, BETA_FULL, NET_CARRY_USD_BP)
        out[f"gamma_{gamma}"] = (kappa_with_qf - kappa_no_qf) * 1e4
    out["gamma_1_times_0.5"] = out["gamma_0.5"] / 0.5 if out["gamma_0.5"] else None
    out["matches_linearity"] = bool(
        out["gamma_0.0"] == 0.0 or abs(out["gamma_0.0"]) < 1e-10
    ) and bool(abs(out["gamma_0.5"] - 0.5 * out["gamma_1.0"]) < 1e-8)
    return out


def _plot_figure2(rows: list[dict]) -> Path:
    fig, ax = plt.subplots(figsize=(7, 5))
    for sigma_bar in EXP3_SIGMA_BAR_GRID:
        sub = sorted((r for r in rows if r["sigma_bar"] == sigma_bar), key=lambda r: r["rho_23"])
        x = [r["rho_23"] for r in sub]
        y = [r["quanto_adjustment_usd_collateral_bp"] for r in sub]
        ax.plot(x, y, marker="o", label=f"sigma_bar={sigma_bar * 100:.1f}%")
    ax.axhline(0.0, color="grey", linewidth=0.8)
    ax.axvline(0.0, color="grey", linewidth=0.8)
    ax.set_xlabel("Foreign-rate / FX correlation rho_23")
    ax.set_ylabel("Quanto adjustment to the par margin, bp (USD collateral, gamma=1)")
    ax.set_title("Figure 2: contractual quanto adjustment")
    ax.legend()
    fig.tight_layout()
    out_path = Path(__file__).resolve().parent.parent / "results" / "exp3_figure2_quanto_adjustment.png"
    fig.savefig(out_path, dpi=150)
    plt.close(fig)
    return out_path


def main() -> None:
    results_dir = Path(__file__).resolve().parent.parent / "results"
    results_dir.mkdir(parents=True, exist_ok=True)

    rows = run_sensitivity()
    print("Figure 2 - quanto adjustment to the par margin (bp), 5Y swap, gamma=1:")
    for row in rows:
        print(f"  rho_23={row['rho_23']:+.2f} sigma_bar={row['sigma_bar']*100:4.1f}% "
              f"usd={row['quanto_adjustment_usd_collateral_bp']:+.4f}bp "
              f"eur={row['quanto_adjustment_eur_collateral_bp']:+.4f}bp "
              f"|usd-eur|={row['usd_eur_abs_diff_bp']:.5f}bp")

    linearity = run_gamma_linearity_check()
    print(f"Gamma-linearity check: {linearity}")

    plot_path = _plot_figure2(rows)
    print(f"Saved {plot_path}")

    max_usd_eur_diff = max(r["usd_eur_abs_diff_bp"] for r in rows)
    zero_row = next(r for r in rows if r["rho_23"] == 0.0 and abs(r["sigma_bar"] - 0.075) < 1e-12)

    results = {
        "experiment": "exp_3_contractual_quanto_adjustment",
        "maturity_years": EXP3_MATURITY,
        "gamma": EXP3_GAMMA,
        "sensitivity_grid": rows,
        "max_usd_eur_collateral_abs_diff_bp": max_usd_eur_diff,
        "adjustment_at_rho23_zero_bp": zero_row["quanto_adjustment_usd_collateral_bp"],
        "gamma_linearity_check": linearity,
    }
    out_json = results_dir / "exp3_quanto_adjustment.json"
    out_json.write_text(json.dumps(results, indent=2))
    print(f"Saved {out_json}")

    out_csv = results_dir / "exp3_figure2.csv"
    with open(out_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    print(f"Saved {out_csv}")


if __name__ == "__main__":
    main()
